function t(key){
  const lang = localStorage.getItem('saarthi_lang_v2') || 'en';
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function applyI18n(lang){
  const dict = I18N[lang] || I18N.en;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-opt').forEach(b => b.classList.toggle('on', b.dataset.lang === lang));
  const cur = document.getElementById('langCur');
  if (cur) cur.textContent = { en:'EN', pa:'ਪਾ', hi:'हि' }[lang];
}

function initI18nSwitcher(onChange){
  const saved = localStorage.getItem('saarthi_lang_v2') || 'en';
  applyI18n(saved);
  document.querySelectorAll('.lang-opt').forEach(b =>
    b.addEventListener('click', () => {
      if (b.dataset.lang === (localStorage.getItem('saarthi_lang_v2') || 'en')) return;
      localStorage.setItem('saarthi_lang_v2', b.dataset.lang);
      applyI18n(b.dataset.lang);
      // Re-render in place instead of reloading the page — this is what keeps you
      // on the exact tab/section you were viewing when you switch language, and
      // is also what lets dynamically-generated content (tables, statuses, KPI
      // numbers) pick up the new language immediately.
      if (typeof onChange === 'function') onChange();
    }));
}
